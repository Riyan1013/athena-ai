import assert from 'node:assert/strict'
import type { AIProvider } from '../ai/providers/AIProvider.js'
import { ConversationManager } from '../conversation/ConversationManager.js'
import { Athena } from '../core/Athena.js'
import type { MemoryRepository } from '../memory/MemoryRepository.js'
import { InMemoryMemoryRepository } from '../memory/InMemoryMemoryRepository.js'
import { MemoryManager } from '../memory/MemoryManager.js'

/**
 * Local, dependency-free test suite for Athena.summarizeConversation().
 *
 * Uses a fake AIProvider that records prompts/token limits and returns
 * fixed or scripted responses, plus InMemoryMemoryRepository behind
 * MemoryManager. No network, no Gemini, no RPD consumed.
 */

type TestFn = () => Promise<void> | void

interface TestCase {
  name: string
  fn: TestFn
}

const tests: TestCase[] = []

function test(name: string, fn: TestFn): void {
  tests.push({ name, fn })
}

/**
 * Fake AIProvider that records every call and returns responses from a
 * queue (or a single fixed response if never queued), or throws if
 * configured to fail. Never calls Gemini or any network service.
 */
class FakeAIProvider implements AIProvider {
  readonly capturedPrompts: string[] = []
  readonly capturedMaxOutputTokens: number[] = []
  private readonly responseQueue: string[] = []
  private failNext = false
  private failError: Error = new Error('Simulated provider failure')

  async generateResponse(
    prompt: string,
    maxOutputTokens: number,
  ): Promise<string> {
    this.capturedPrompts.push(prompt)
    this.capturedMaxOutputTokens.push(maxOutputTokens)

    if (this.failNext) {
      this.failNext = false
      throw this.failError
    }

    const queued = this.responseQueue.shift()
    return queued ?? 'Default fixed summary response.'
  }

  queueResponse(response: string): void {
    this.responseQueue.push(response)
  }

  failOnNextCall(error: Error = new Error('Simulated provider failure')): void {
    this.failNext = true
    this.failError = error
  }

  get callCount(): number {
    return this.capturedPrompts.length
  }

  get lastPrompt(): string {
    const prompt = this.capturedPrompts.at(-1)
    assert.ok(
      prompt !== undefined,
      'Expected generateResponse to have been called',
    )
    return prompt as string
  }

  get lastMaxOutputTokens(): number {
    const value = this.capturedMaxOutputTokens.at(-1)
    assert.ok(
      value !== undefined,
      'Expected generateResponse to have been called',
    )
    return value as number
  }
}

/** Fresh Athena instance for each test, backed by a real in-memory repository. */
function makeAthena(): {
  athena: Athena
  provider: FakeAIProvider
  conversationManager: ConversationManager
  memoryManager: MemoryManager
} {
  const provider = new FakeAIProvider()
  const conversationManager = new ConversationManager()
  const repository: MemoryRepository = new InMemoryMemoryRepository()
  const memoryManager = new MemoryManager(repository)
  const athena = new Athena(provider, conversationManager, memoryManager)

  return { athena, provider, conversationManager, memoryManager }
}

// ---------------------------------------------------------------------
// 1. Generates a summary from actual conversation messages
// ---------------------------------------------------------------------

test('summarizeConversation() generates a summary from actual conversation messages', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  const conversation = conversationManager.getOrCreate('conv-1')
  conversation.addMessage('user', 'My favorite color is blue.')
  conversation.addMessage('assistant', 'Noted, blue it is.')

  provider.queueResponse('The user said their favorite color is blue.')

  const result = await athena.summarizeConversation('conv-1', 'user-1')

  assert.equal(result.type, 'CONVERSATION_SUMMARY')
  assert.equal(result.content, 'The user said their favorite color is blue.')
  assert.ok(provider.lastPrompt.includes('My favorite color is blue.'))
  assert.ok(provider.lastPrompt.includes('Noted, blue it is.'))
})

// ---------------------------------------------------------------------
// 2. The provider receives the prompt generated by buildSummaryPrompt()
// ---------------------------------------------------------------------

test('the provider receives a prompt built by buildSummaryPrompt()', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  const conversation = conversationManager.getOrCreate('conv-1')
  conversation.addMessage('user', 'Hello there.')

  await athena.summarizeConversation('conv-1', 'user-1')

  // buildSummaryPrompt()'s known, distinctive instruction text should
  // appear verbatim in the prompt sent to the provider.
  assert.ok(
    provider.lastPrompt.includes(
      'Respond with ONLY the summary text. Do not include any preamble,\nheadings, or explanation.',
    ),
  )
  assert.ok(provider.lastPrompt.includes('Transcript:'))
  assert.ok(provider.lastPrompt.includes('User:\nHello there.'))
})

// ---------------------------------------------------------------------
// 3. SUMMARY_TOKEN_LIMIT (300) is passed to generateResponse()
// ---------------------------------------------------------------------

test('SUMMARY_TOKEN_LIMIT (300) is passed as maxOutputTokens', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')

  await athena.summarizeConversation('conv-1', 'user-1')

  assert.equal(provider.lastMaxOutputTokens, 300)
})

// ---------------------------------------------------------------------
// 4. Successful generation creates the conversation summary
// ---------------------------------------------------------------------

test('successful generation creates the conversation summary', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')
  provider.queueResponse('A brand new summary.')

  const before = await athena.getConversationSummary('user-1', 'conv-1')
  assert.equal(before, undefined)

  await athena.summarizeConversation('conv-1', 'user-1')

  const after = await athena.getConversationSummary('user-1', 'conv-1')
  assert.equal(after?.content, 'A brand new summary.')
})

// ---------------------------------------------------------------------
// 5. Calling it again updates the existing summary rather than
// creating another one
// ---------------------------------------------------------------------

test('calling summarizeConversation() again updates the existing summary', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')

  provider.queueResponse('First summary.')
  const first = await athena.summarizeConversation('conv-1', 'user-1')

  provider.queueResponse('Second summary.')
  const second = await athena.summarizeConversation('conv-1', 'user-1')

  assert.equal(second.id, first.id)
  assert.equal(second.createdAt, first.createdAt)
  assert.equal(second.content, 'Second summary.')

  const stored = await athena.getConversationSummary('user-1', 'conv-1')
  assert.equal(stored?.content, 'Second summary.')
})

// ---------------------------------------------------------------------
// 6. Existing summary is included in the second summarization prompt
// ---------------------------------------------------------------------

test('the existing summary is included in the second summarization prompt', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')

  provider.queueResponse('The user said hello.')
  await athena.summarizeConversation('conv-1', 'user-1')

  provider.queueResponse('Updated summary.')
  await athena.summarizeConversation('conv-1', 'user-1')

  assert.ok(provider.lastPrompt.includes('Previous summary'))
  assert.ok(provider.lastPrompt.includes('The user said hello.'))
})

// ---------------------------------------------------------------------
// 7. Provider failure rejects and leaves the previous summary unchanged
// ---------------------------------------------------------------------

test('provider failure rejects and leaves the previous summary unchanged', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')

  provider.queueResponse('Original summary.')
  await athena.summarizeConversation('conv-1', 'user-1')

  provider.failOnNextCall()
  await assert.rejects(() => athena.summarizeConversation('conv-1', 'user-1'))

  const stored = await athena.getConversationSummary('user-1', 'conv-1')
  assert.equal(stored?.content, 'Original summary.')
})

// ---------------------------------------------------------------------
// 8. Provider failure when no summary exists leaves no summary
// ---------------------------------------------------------------------

test('provider failure with no existing summary leaves no summary', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')

  provider.failOnNextCall()
  await assert.rejects(() => athena.summarizeConversation('conv-1', 'user-1'))

  const stored = await athena.getConversationSummary('user-1', 'conv-1')
  assert.equal(stored, undefined)
})

// ---------------------------------------------------------------------
// 9. Different users remain isolated
// ---------------------------------------------------------------------

test("different users' summaries remain isolated", async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-shared').addMessage('user', 'Hi.')

  provider.queueResponse("User A's summary.")
  await athena.summarizeConversation('conv-shared', 'user-a')

  provider.queueResponse("User B's summary.")
  await athena.summarizeConversation('conv-shared', 'user-b')

  const summaryA = await athena.getConversationSummary('user-a', 'conv-shared')
  const summaryB = await athena.getConversationSummary('user-b', 'conv-shared')

  assert.equal(summaryA?.content, "User A's summary.")
  assert.equal(summaryB?.content, "User B's summary.")
  assert.notEqual(summaryA?.id, summaryB?.id)
})

// ---------------------------------------------------------------------
// 10. Different conversation IDs remain independent
// ---------------------------------------------------------------------

test('different conversation IDs for the same user remain independent', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-a').addMessage('user', 'About A.')
  conversationManager.getOrCreate('conv-b').addMessage('user', 'About B.')

  provider.queueResponse('Summary of conversation A.')
  await athena.summarizeConversation('conv-a', 'user-1')

  provider.queueResponse('Summary of conversation B.')
  await athena.summarizeConversation('conv-b', 'user-1')

  const summaryA = await athena.getConversationSummary('user-1', 'conv-a')
  const summaryB = await athena.getConversationSummary('user-1', 'conv-b')

  assert.equal(summaryA?.content, 'Summary of conversation A.')
  assert.equal(summaryB?.content, 'Summary of conversation B.')
  assert.notEqual(summaryA?.id, summaryB?.id)
})

// ---------------------------------------------------------------------
// 11. Conversation messages are unchanged after summarization
// ---------------------------------------------------------------------

test('conversation messages are unchanged after summarization', async () => {
  const { athena, conversationManager } = makeAthena()

  const conversation = conversationManager.getOrCreate('conv-1')
  conversation.addMessage('user', 'First message.')
  conversation.addMessage('assistant', 'First reply.')

  const before = conversation.getMessages().length

  await athena.summarizeConversation('conv-1', 'user-1')

  const after = conversation.getMessages().length
  assert.equal(after, before)
  assert.equal(after, 2)
})

// ---------------------------------------------------------------------
// 12. summarizeConversation() does not call any explicit-memory APIs
// ---------------------------------------------------------------------

test('summarizeConversation() does not create/modify explicit memories', async () => {
  const { athena, conversationManager } = makeAthena()

  conversationManager.getOrCreate('conv-1').addMessage('user', 'Hi.')

  const before = await athena.listMemories('user-1')
  assert.equal(before.length, 0)

  await athena.summarizeConversation('conv-1', 'user-1')

  const after = await athena.listMemories('user-1')
  assert.equal(after.length, 0)
})

// ---------------------------------------------------------------------
// 13. Existing ask() behavior remains unaffected
// ---------------------------------------------------------------------

test('ask() behavior is unaffected by the existence of summarizeConversation()', async () => {
  const { athena, provider, conversationManager } = makeAthena()

  provider.queueResponse('An ordinary ask() reply.')
  const response = await athena.ask('conv-1', 'user-1', 'Hello there.')

  assert.equal(response, 'An ordinary ask() reply.')

  const conversation = conversationManager.get('conv-1')
  assert.equal(conversation?.getMessages().length, 2)
  assert.equal(conversation?.getMessages()[0]?.role, 'user')
  assert.equal(conversation?.getMessages()[1]?.role, 'assistant')

  // ask() must never itself have created a summary.
  const summary = await athena.getConversationSummary('user-1', 'conv-1')
  assert.equal(summary, undefined)
})

// ---------------------------------------------------------------------
// Runner
// ---------------------------------------------------------------------

async function run(): Promise<void> {
  let passed = 0
  let failed = 0

  for (const { name, fn } of tests) {
    try {
      await fn()
      passed++
      console.log(`✅ ${name}`)
    } catch (error) {
      failed++
      console.log(`❌ ${name}`)
      console.log(error instanceof Error ? error.message : String(error))
    }
  }

  const total = passed + failed
  console.log(`🦉 Results: ${passed} passed, ${failed} failed, ${total} total`)

  if (failed > 0) {
    process.exit(1)
  }
}

run()
